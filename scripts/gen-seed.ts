// Generates supabase/seed.sql from the curriculum.
// Run: node --experimental-strip-types scripts/gen-seed.ts
import { writeFileSync } from "node:fs";
import { ALL_PROMPTS } from "../src/lib/curriculum.ts";

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]`;

const rows = ALL_PROMPTS.map(
  (p) =>
    `  (${p.id}, ${q(p.level)}, ${q(p.goal)}, ${p.day_index}, ${q(p.title)}, ${arr(p.talking_points)}, ${q(p.skill)}, ${q(p.skill_tip)}, ${p.week}, ${q(p.focus)}, ${p.milestone})`,
);

const sql = `-- Generated by scripts/gen-seed.ts from src/lib/curriculum.ts. Do not edit by hand.
-- ${ALL_PROMPTS.length} prompts: 3 levels x 5 goals x 30 days. {niche} is filled in by the app.
insert into public.prompts overriding system value
  (id, level, goal, day_index, title, talking_points, skill, skill_tip, week, focus, milestone)
values
${rows.join(",\n")}
on conflict (id) do update set
  title = excluded.title, talking_points = excluded.talking_points, skill = excluded.skill,
  skill_tip = excluded.skill_tip, week = excluded.week, focus = excluded.focus, milestone = excluded.milestone;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${ALL_PROMPTS.length} prompts to supabase/seed.sql`);
